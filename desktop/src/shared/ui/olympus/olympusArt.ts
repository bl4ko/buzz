function meander() {
  const { cx, cy } = OLYMPUS_RING;
  const step = (2 * Math.PI) / 28;
  const at = (r: number, a: number) =>
    `${(cx + r * Math.cos(a)).toFixed(1)},${(cy + r * Math.sin(a)).toFixed(1)}`;
  let d = "";
  for (let i = 0; i < 28; i++) {
    const a = step * i - Math.PI / 2;
    d += `M${at(326, a)} L${at(362, a)} A362,362 0 0 1 ${at(362, a + step * 0.7)} L${at(338, a + step * 0.7)} A338,338 0 0 0 ${at(338, a + step * 0.32)} L${at(350, a + step * 0.32)} `;
  }
  return d.trim();
}

