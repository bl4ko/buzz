type Bump = [x: number, y: number, r: number];

function cloud(x: number, y: number, bumps: Bump[], bottom?: number) {
  const arcs = bumps.map(([bx, by, r]) => `A${r},${r} 0 0 1 ${bx},${by}`);
  const close = bottom === undefined ? "Z" : `V${bottom} H${x} Z`;
  return `M${x},${y} ${arcs.join(" ")} ${close}`;
}

